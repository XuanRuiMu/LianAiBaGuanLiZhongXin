class TestDSL版本:
    def test_导入导出幂等(self, tmp_path):
        _, 存储, _ = 建引擎(tmp_path)
        流程 = 流程定义.model_validate(五节点流程())
        文本一 = 存储.导出YAML(流程)
        流程二 = 存储.从YAML导入(文本一)
        assert 存储.导出YAML(流程二) == 文本一
        assert "开始" in 文本一

    def test_版本递增回滚与差异(self, tmp_path):
        _, 存储, _ = 建引擎(tmp_path)
        流程 = 流程定义.model_validate(五节点流程())
        版一 = 存储.保存版本(流程)
        流程.节点.append({"编号": "新增", "类型": "代码", "参数": {"表达式": "9"}})
        版二 = 存储.保存版本(流程)
        assert (版一, 版二) == (1, 2)
        差异 = 存储.版本差异("演示流程", 1, 2)
        assert any("新增" in 行 for 行 in 差异)
        回滚 = 存储.取版本("演示流程", 1)
        assert all(节点.编号 != "新增" for 节点 in 回滚.节点)
        最新 = 存储.取版本("演示流程")
        assert 最新.版本 == 2

    def test_YAML非法拒绝(self, tmp_path):
        _, 存储, _ = 建引擎(tmp_path)
        with pytest.raises(ValueError):
            存储.从YAML导入("- 1\n- 2\n")
