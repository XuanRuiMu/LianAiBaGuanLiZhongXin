class Test求值器:
    def test_路径与条件(self):
        assert 取路径({"甲": {"乙": 3}}, "$.甲.乙") == 3
        assert 取路径({"甲": 1}, "$.缺失") is None
        assert 条件成立(5, ">", 3) is True
        assert 条件成立("甲", "包含", "乙") is False

    def test_危险表达式拒绝(self):
        with pytest.raises(ValueError):
            安全求值("__import__('os').system('x')", {})
        with pytest.raises(ValueError):
            安全求值("[x for x in range(3)]", {})
        assert 安全求值("1 + 2 == 3 and True", {}) is True


