def 建引擎(tmp_path, **kwargs):
    存储 = 编排存储(str(tmp_path / "编排.db"))
    追踪 = 追踪存储(str(tmp_path / "追踪.db"))
    参数 = {"退避基数": 0}
    参数.update(kwargs)
    return 编排引擎(存储, 追踪, 注册表, **参数), 存储, 追踪


