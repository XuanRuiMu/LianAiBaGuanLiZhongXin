def 提取文本(内容) -> str:
    if isinstance(内容, str):
        return 内容
    if isinstance(内容, list):
        return "".join(
            片段.get("text", "")
            for 片段 in 内容
            if isinstance(片段, dict) and isinstance(片段.get("text"), str)
        )
    return ""
